"""connectivity.py - the ping and traceroute test plan, with the answers worked out in advance.

ITN module 13 (ICMP: ping, traceroute) and 17.4 (testing connectivity, extended ping). For each
VLAN the plan lists what to type on a host and what must come back: which gateway answers,
which addresses tracert shows hop by hop, in IPv4 and IPv6. The expected hops come from the
routing simulator (routing.py), so they follow the generated configurations; the failure
scenarios show how the path changes when an uplink or a switch is down. Extended pings from
the routers test a return path without a PC: the source address decides where the reply goes.

Saved outputs are checked by `python -m campus verify` (see verify.py): a tracert must pass
through the expected devices in order, a ping must get replies.
"""
import ipaddress

from .routing import SCENARIOS, Lab


def hsrp6_link_local(group):
    """HSRP version 2 IPv6: virtual MAC 0005.73a0.0000 + group, link-local by EUI-64."""
    return ipaddress.ip_address(f"fe80::205:73ff:fea0:{group:x}")


def expected_tracert(net, vlan_id, family, down=()):
    """[(device, address that answers)] from a host in the VLAN to the server; None if not delivered."""
    lab = Lab(net, down)
    ok, _ = lab.trace(f"vlan{vlan_id}", "server", family)
    if not ok:
        return None
    srv = lab.server(family)
    return [(d, a) for d, a in lab.path] + [(net.raw["isp"]["server"]["name"], srv)]


def extended_pings(net):
    """[(device, command, source address, destination, ok)] - the router-side tests."""
    lab = Lab(net)
    srv4, srv6 = lab.server(4), lab.server(6)
    r1 = net.raw["routers"]["R1"]
    lo4 = ipaddress.ip_interface(r1["loopback"]["v4"]).ip
    lo6 = ipaddress.ip_interface(r1["loopback"]["v6"]).ip
    out = [("R1", f"ping {srv4} source Loopback0", lo4, srv4),
           ("R1", f"ping ipv6 {srv6} source Loopback0", lo6, srv6)]
    a = net.raw["addressing"]
    for i, d in enumerate(net.dist()):
        v = next(v for v in sorted(net.routed_vlans, key=lambda v: v.id) if v.primary == d)
        n = a["d1_host"] if i == 0 else a["d2_host"]
        out += [(d, f"ping {srv4} source Vlan{v.id}", v.host(n), srv4),
                (d, f"ping ipv6 {srv6} source Vlan{v.id}", v.host6(n), srv6)]
    return [(dev, cmd, s, t, lab.ping(dev, str(s), str(t))[0]) for dev, cmd, s, t in out]


def report(net):
    a = net.raw["addressing"]
    isp = net.raw["isp"]
    srv4, srv6 = ipaddress.ip_address(isp["server"]["v4"]), ipaddress.ip_address(isp["server"]["v6"])
    vlans = sorted(net.routed_vlans, key=lambda v: v.id)
    out = ["# Connectivity tests: ping and tracert", "",
           "Generated by `python -m campus connectivity` from the generated configurations (ITN 13 and 17.4).",
           "The expected hops are what the routing simulator computes; the lab must show the same. On a",
           "Windows PC `tracert -d` skips the name lookups (Packet Tracer's PCs take plain `tracert`).", "",
           "## 1. From a host in each VLAN", "",
           "| VLAN | Host gets | Ping the gateway | Default gateway in `ipconfig` (IPv6) | Ping across VLANs |",
           "| ---: | --- | --- | --- | --- |"]
    known = []                                   # fixed addresses to ping across VLANs
    if net.raw.get("wlc"):
        w = net.raw["wlc"]
        known.append((ipaddress.ip_interface(w["mgmt"]).ip, w["name"]))
    known += [(ipaddress.ip_address(r["ip"]), r["name"]) for r in net.raw.get("dhcp_reservations", [])]
    for v in vlans:
        target = next(((ip, n) for ip, n in known if ip not in v.v4), None)
        across = (f"`ping {target[0]}` ({target[1]})" if target else
                  f"`ping {next(o for o in vlans if o.id != v.id).host(a['gateway_host'])}`")
        got = "static (no DHCP)" if not v.dhcp else (
            f"{v.v4.network_address + a['dhcp_excluded_last'] + 1} - {v.v4.broadcast_address - 1}")
        out.append(f"| {v.id} | {got} | `ping {v.host(a['gateway_host'])}` | "
                   f"{str(hsrp6_link_local(1000 + v.id)).upper()} (HSRP group {1000 + v.id}) | "
                   f"{across} |")
    out += ["", "The IPv6 default gateway is the HSRP group's virtual link-local address, learned from the",
            "router advertisements: version 2 groups use the virtual MAC 0005.73A0.0000 plus the group number,",
            "and the link-local address is built from it by EUI-64. `show standby` on the active switch shows it.", "",
            "## 2. To the dual-stack server, everything up", "",
            f"`ping {srv4}`, `ping {srv6}`, then `tracert -d {srv4}` and `tracert -d {srv6}`. Each hop is the address",
            "of the interface the probe arrived on; the first hop is the active switch's own SVI address, not",
            "the HSRP virtual address.", ""]
    for v in vlans:
        cells = []
        for fam in (4, 6):
            hops = expected_tracert(net, v.id, fam)
            cells.append("<br>".join(f"{i}. {addr} ({dev})" for i, (dev, addr) in enumerate(hops, 1))
                         if hops else "NOT delivered")
        out.append(f"**VLAN {v.id} {v.name}**" + "\n\n| IPv4 | IPv6 |\n| --- | --- |\n| " + " | ".join(cells) + " |\n")
    out += ["## 3. The same tracert with a link or a switch down", "",
            "Devices the IPv4 tracert passes through (IPv6 takes the same path). Run it during the failover",
            "tests of the lab-day sheet.", "",
            "| Scenario | " + " | ".join(f"VLAN {v.id}" for v in vlans) + " |",
            "| --- | " + " | ".join("---" for _ in vlans) + " |"]
    for down, label in SCENARIOS:
        cells = []
        for v in vlans:
            hops = expected_tracert(net, v.id, 4, down)
            cells.append(" > ".join(d for d, _ in hops[:-1]) if hops else "NOT delivered")
        out.append(f"| {label} | " + " | ".join(cells) + " |")
    out += ["", "## 4. Extended ping from the routers", "",
            "A plain ping from R1 leaves through G0/0 with the source 203.0.113.2, which the ISP reaches",
            "without any route, so it proves little. With a source inside the site the reply has to find",
            "its way back through the ISP's route to the site block and R1's routes into the campus; from a",
            "distribution switch, sourcing the ping from an SVI tests a VLAN's return path without a PC.", "",
            "| Device | Command | Source | Simulated |", "| --- | --- | --- | --- |"]
    for dev, cmd, src, dst, ok in extended_pings(net):
        out.append(f"| {dev} | `{cmd}` | {src} | {'replies' if ok else 'NO reply'} |")
    out += ["", "On IOS: `!` is a reply, `.` a timeout, `U` an unreachable sent back by a router. The first",
            "ping to a new neighbour often loses one packet while ARP (or neighbour discovery) resolves.", "",
            "## 5. Saving the outputs for `verify`", "",
            "Copy each output into `captures/` (or save it with PuTTY's log):", "",
            "| File | Command |", "| --- | --- |",
            f"| `vlan10_ping_server.txt` | `ping {srv4}` on a VLAN 10 host |",
            f"| `vlan10_ping6_server.txt` | `ping {srv6}` |",
            f"| `vlan10_tracert_server.txt` | `tracert -d {srv4}` |",
            f"| `vlan10_tracert6_server.txt` | `tracert -d {srv6}` |",
            "| `R1_ping_server_source_Loopback0.txt` | the extended ping from R1 |", "",
            "The same names work for every VLAN (`vlan30_...`) and device (`D2_ping_...`). `python -m campus",
            "verify captures` checks that each tracert passes through the devices above in order and that",
            "each ping got replies."]
    return "\n".join(out) + "\n"
