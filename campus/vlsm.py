"""vlsm.py - size every subnet from the number of hosts it has to hold (ITN module 11).

The design gives every VLAN a /24 whose third octet is the VLAN number (10.20.30.0/24 is VLAN
30), because that is easy to read in a show command at 3 a.m. This module does the calculation
the other way round, the way ITN 11 teaches it: take the hosts each VLAN must hold, add the
growth margin, find the smallest prefix that fits, and allocate the biggest subnets first so
every subnet starts on its own boundary (variable-length subnet masking). The report puts the
two side by side: how much of the /17 each plan uses, and that every /24 really holds its hosts.

Point-to-point links need two addresses: a /30 has two usable hosts, a /31 (RFC 3021) has two
addresses and no network or broadcast address, so it wastes nothing.
"""
import ipaddress
import math

RESERVED = 3        # HSRP virtual address + D1's SVI + D2's SVI in every VLAN


def with_growth(hosts, growth_percent):
    return math.ceil(hosts * (100 + growth_percent) / 100)


def usable(prefix):
    """Usable host addresses in an IPv4 subnet of this length."""
    if prefix == 32:
        return 1
    if prefix == 31:
        return 2                                    # RFC 3021: both addresses are hosts
    return 2 ** (32 - prefix) - 2


def prefix_for(needed, allow_31=False):
    """Longest prefix whose usable addresses hold `needed` (2 -> /30, or /31 if allowed)."""
    for p in range(32, 0, -1):
        if p == 31 and not allow_31:
            continue
        if p == 32 and needed > 1:
            continue
        if usable(p) >= needed:
            return p
    raise ValueError(f"{needed} hosts do not fit in IPv4")


def capacity(net, v):
    """End devices the VLAN's subnet can hold as designed: the DHCP pool, or everything but the
    gateway addresses for a VLAN without DHCP."""
    a = net.raw["addressing"]
    if v.dhcp:
        return v.v4.num_addresses - 2 - a["dhcp_excluded_last"]
    return v.v4.num_addresses - 2 - RESERVED


def allocate(block, requests):
    """VLSM: [(label, needed addresses)] -> [(label, subnet)], biggest first, each subnet on its
    own boundary, packed from the start of `block`. Raises ValueError if it does not fit."""
    out, nxt = [], int(block.network_address)
    order = sorted(requests, key=lambda r: (-r[1], str(r[0])))
    for label, size in order:
        size = 2 ** math.ceil(math.log2(size))
        start = math.ceil(nxt / size) * size        # align to the subnet's own size
        sub = ipaddress.ip_network((start, 32 - int(math.log2(size))))
        if not sub.subnet_of(block):
            raise ValueError(f"{label} does not fit in {block}")
        out.append((label, sub))
        nxt = start + size
    return out


def plan_vlsm(net, allow_31=False):
    """{'vlans': [(vlan, hosts, needed, prefix, vlsm subnet)], 'links': [(name, subnet)], 'block': ...}"""
    a = net.raw["addressing"]
    g = a.get("growth_percent", 0)
    r1 = net.raw["routers"]["R1"]
    block = ipaddress.ip_network(r1["campus_summary"]["v4"])
    rows, reqs = {}, []
    for v in sorted(net.routed_vlans, key=lambda v: v.id):
        if v.hosts is None:
            continue
        need = with_growth(v.hosts, g) + RESERVED
        p = prefix_for(need)
        rows[v.id] = [v, v.hosts, need, p, None]
        reqs.append((v.id, 2 ** (32 - p)))
    links = [f"R1 {ifn} - {i['peer']}" for ifn, i in r1["interfaces"].items() if "peer" in i]
    lp = prefix_for(2, allow_31)
    reqs += [(name, 2 ** (32 - lp)) for name in links]
    reqs.append(("R1 Loopback0", 1))
    alloc = dict(allocate(block, reqs))
    for vid, r in rows.items():
        r[4] = alloc[vid]
    used = sum(s.num_addresses for s in alloc.values())
    return {"vlans": list(rows.values()), "links": [(n, alloc[n]) for n in links],
            "loopback": alloc["R1 Loopback0"], "block": block, "used": used,
            "smallest_block": ipaddress.ip_network((int(block.network_address), 32 - math.ceil(math.log2(used)))),
            "growth": g, "link_prefix": lp}


def report(net):
    a = net.raw["addressing"]
    vl, v31 = plan_vlsm(net), plan_vlsm(net, allow_31=True)
    g = vl["growth"]
    out = ["# VLSM: subnets sized from the hosts they hold", "",
           "Generated by `python -m campus vlsm` from network.yaml (ITN module 11). Each VLAN's `hosts` is the",
           f"number of devices expected at the real site; every subnet must hold them plus {g}% growth plus",
           f"{RESERVED} addresses for the gateways (HSRP virtual address, D1 and D2).", "",
           "## Step 1: how big must each subnet be", "",
           "| VLAN | Name | Hosts | + growth + gateways | Smallest prefix | Usable in it |",
           "| ---: | --- | ---: | ---: | --- | ---: |"]
    for v, hosts, need, p, _ in vl["vlans"]:
        out.append(f"| {v.id} | {v.name} | {hosts} | {need} | /{p} ({ipaddress.ip_network(f'0.0.0.0/{p}').netmask}) | {usable(p)} |")
    big = max(vl["vlans"], key=lambda r: r[2])
    v, hosts, need, p, _ = big
    out += ["", f"Worked example, VLAN {v.id}: {hosts} hosts + {g}% = {need - RESERVED}, + {RESERVED} gateways = {need}. "
            f"2^{32 - p - 1} - 2 = {2 ** (32 - p - 1) - 2} is too few, 2^{32 - p} - 2 = {usable(p)} is enough, "
            f"so {32 - p} host bits and a /{p}.", "",
            "## Step 2: allocate the biggest first", "",
            f"Packed from the start of the campus block {vl['block']}, biggest subnet first, so each one",
            "starts on a multiple of its own size and nothing overlaps.", "",
            "| Subnet for | VLSM subnet | Range | Broadcast |", "| --- | --- | --- | --- |"]
    rows = [(f"VLAN {r[0].id} {r[0].name}", r[4]) for r in vl["vlans"]] + vl["links"] + [("R1 Loopback0", vl["loopback"])]
    for name, s in sorted(rows, key=lambda r: int(r[1].network_address)):
        rng = (f"{s.network_address + 1} - {s.broadcast_address - 1}" if s.prefixlen < 31
               else str(s.network_address) if s.prefixlen == 32 else f"{s.network_address} - {s.broadcast_address}")
        bc = str(s.broadcast_address) if s.prefixlen < 31 else "-"
        out.append(f"| {name} | {s} | {rng} | {bc} |")
    out += ["", f"Everything fits in {vl['used']} addresses, a {vl['smallest_block']} would hold it.", "",
            "## Step 3: the design keeps /24s, and they are big enough", "",
            "| VLAN | Design subnet | Room for end devices | Needed with growth | Used |",
            "| ---: | --- | ---: | ---: | ---: |"]
    fixed, full = 0, []
    for v, hosts, need, p, _ in vl["vlans"]:
        room, n = capacity(net, v), need - RESERVED
        fixed += v.v4.num_addresses
        where = "DHCP pool" if v.dhcp else "static"
        out.append(f"| {v.id} | {v.v4} | {room} ({where}) | {n} | {round(100 * n / room)}% |")
        if n / room >= 0.9:
            full.append(f"VLAN {v.id} ({v.name}) is close to full with the growth margin: past {room} devices it "
                        f"needs a /{v.v4.prefixlen - 1} (renumbering) or a second VLAN.")
    pool = min(capacity(net, r[0]) for r in vl["vlans"] if r[0].dhcp)
    out += [""] + full + (["" ] if full else []) + [
            f"The /24 plan takes {fixed} addresses for the VLANs, VLSM would take "
            f"{sum(r[4].num_addresses for r in vl['vlans'])}. Both use a small part of {vl['block']} "
            f"({vl['block'].num_addresses} addresses),",
            "so the design spends addresses on readability: the third octet is the VLAN number, every VLAN",
            f"has the same .{a['gateway_host']} gateway and .{a['dhcp_excluded_last'] + 1}-.254 pool, and each DHCP VLAN can grow to {pool} devices",
            "without renumbering. VLSM matters when the block is small (a /24 split into VLANs, or public",
            "addresses).", "",
            "## Point-to-point links: /30 or /31", "",
            "| Link | /30 (design) | /31 (RFC 3021) |", "| --- | --- | --- |"]
    for (name, s30), (_, s31) in zip(vl["links"], v31["links"]):
        out.append(f"| {name} | {s30}: {s30.network_address + 1} and {s30.network_address + 2}, "
                   f"2 of 4 addresses usable | {s31}: {s31.network_address} and {s31.broadcast_address}, both usable |")
    out += ["", "A /31 halves the addresses a link takes. The design keeps /30s: they are what ITN and SRWE",
            "use, and every device in the lab accepts them.", "",
            "## IPv6: no VLSM needed", "",
            f"The campus has {net.raw['routers']['R1']['campus_summary']['v6']}: 2^(64-56) = 256 subnets of /64. Every VLAN gets a /64",
            "whatever its size (SLAAC needs a 64-bit interface ID), and the subnet ID is the VLAN number",
            "written in hex digits: VLAN 30 is 2001:db8:acad:30::/64."]
    return "\n".join(out) + "\n"
